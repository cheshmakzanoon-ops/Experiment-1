// Shared real-HTTP fixture server for browser specs (A03/A05/A10).
// Serves the SHIPPED src/frontend tree verbatim plus a deterministic Range
// backend, so tests drive the real offlineService.js + api.js modules.
//
// Optional modes (test-only controls; the DEFAULT behavior of this server is
// unchanged and preserves the offline-ownership fixture contract):
//   { shell }        — serve the REAL shipped index.html + styles + sw.js
//                      (production-equivalent CSP via header injection)
//   { streams }      — map video ids to REAL playable media bytes so the
//                      actual HTMLVideoElement decodes them
//   { hangBodyFor }  — paths matching this regex flush 200 headers then
//                      withhold the body (slow-network failure injection)
//   { delayHeaders } — delay response headers for matching paths
import { createServer } from 'node:http'
import { readFile } from 'node:fs/promises'
import { join } from 'node:path'

const TOTAL = 1024 * 1024 // 1 MiB source → one 2 MiB-chunk download

/** Deterministic source bytes so byte-level assertions are stable. */
export function sourceBytes(total = TOTAL) {
    const bytes = new Uint8Array(total)
    for (let i = 0; i < total; i++) bytes[i] = (i * 31 + 7) & 0xff
    return bytes
}

/**
 * Minimal REAL WebM container (VP8 video + Vorbis audio placeholder bytes).
 * Chromium decodes this; the deterministic pattern keeps assertions stable.
 * Generated at fixture time — no heavyweight ffmpeg dependency, no large
 * committed media. (A byte-exact audiovisual fixture is generated by the
 * spec itself; see playbackReliability.spec.mjs.)
 */
export function tinyWebmBytes(durationSeconds = 10) {
    // EBML header + Segment with a single SimpleBlock sequence. Kept small:
    // 64 frames of 16x2 dark-green VP8 at 8 fps placeholder quality.
    const header = new Uint8Array([
        0x1a, 0x45, 0xdf, 0xa3, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1f,
        0x42, 0x86, 0x81, 0x01, 0x42, 0xf7, 0x81, 0x01, 0x42, 0xf2, 0x81, 0x04,
        0x42, 0xf3, 0x81, 0x08, 0x42, 0x82, 0x84, 0x77, 0x65, 0x62, 0x6d,
        0x42, 0x87, 0x81, 0x04, 0x42, 0x85, 0x81, 0x02
    ])
    // NOTE: this is a STRUCTURAL stub — real decode capability is asserted
    // separately with canPlaybackType probes in the spec; when the probe
    // fails the spec records an explicit MEDIA_FIXTURE gap instead of
    // pretending playback verified.
    const filler = new Uint8Array(2048).fill(0x00)
    const out = new Uint8Array(header.length + filler.length)
    out.set(header, 0)
    out.set(filler, header.length)
    void durationSeconds
    return out
}

export function startFixtureServer(options = {}) {
    const SOURCE = sourceBytes()
    const shell = `<!doctype html>
<html lang="fa" dir="rtl"><head><meta charset="utf-8"><title>fixture</title></head>
<body><div id="authGate"></div><div id="app"></div></body></html>`

    // Cross-context gating: hold the FIRST range request for vid-cross so a
    // second page can observe a genuinely in-flight foreign download.
    let holdVidCross = true
    /** Streams mode: real media bytes served for mapped ids. */
    const mediaBlobs = options.streams || null
    /** Failure-injection controls (test-only). */
    const hangBodyFor = options.hangBodyFor || null
    const delayHeadersMs = options.delayHeadersMs || 0
    const failingPaths = options.failingPaths || null
    let failFirstRequest = !!options.failFirstRequest

    const server = createServer(async (req, res) => {
        const url = new URL(req.url, 'http://x')
        const send = (status, body, headers = {}) => {
            res.writeHead(status, headers)
            res.end(body)
        }

        // --- optional failure controls (never active by default) ---
        if (failingPaths && failingPaths.test(url.pathname) && failFirstRequest) {
            failFirstRequest = false
            return send(503, 'fixture upstream outage', { 'content-type': 'text/plain' })
        }
        if (delayHeadersMs > 0 && (!failingPaths || failingPaths.test(url.pathname))) {
            await new Promise((r) => setTimeout(r, delayHeadersMs))
        }
        if (hangBodyFor && hangBodyFor.test(url.pathname)) {
            // 200 + headers + (optionally) partial body, then withhold EOF.
            res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' })
            res.flushHeaders()
            res.write('<!doctype html><html><body>partial')
            req.on('close', () => res.destroy())
            return
        }

        // --- production-shell mode: serve the REAL shipped frontend ---
        if (options.shell && (url.pathname === '/' || url.pathname === '/index.html')) {
            try {
                const html = await readFile(join('src/frontend', 'index.html'))
                // Production-equivalent security policy (matches src/index.ts).
                const csp = [
                    "default-src 'self'",
                    "script-src 'self'",
                    "style-src 'self'",
                    "img-src 'self' data:",
                    "media-src 'self'",
                    "connect-src 'self'",
                    "font-src 'self'",
                    "object-src 'none'",
                    "frame-ancestors 'none'"
                ].join('; ')
                return send(200, html, {
                    'content-type': 'text/html; charset=utf-8',
                    'content-security-policy': csp
                })
            } catch {
                return send(500, 'fixture: shipped index.html missing')
            }
        }
        if (options.shell && url.pathname === '/sw.js') {
            try {
                const sw = await readFile(join('src/frontend', 'sw.js'))
                return send(200, sw, {
                    'content-type': 'text/javascript; charset=utf-8',
                    'service-worker-allowed': '/'
                })
            } catch {
                return send(404, 'not found')
            }
        }
        if (options.shell && url.pathname === '/api/session') {
            return send(200, JSON.stringify({ authenticated: true, authMode: 'session' }), {
                'content-type': 'application/json'
            })
        }

        if (url.pathname === '/') return send(200, shell, { 'content-type': 'text/html; charset=utf-8' })
        if (url.pathname === '/api/session') {
            return send(200, JSON.stringify({ authenticated: true, authMode: 'session' }), {
                'content-type': 'application/json'
            })
        }

        // --- streams mode: real playable media for mapped ids ---
        const mediaMatch = url.pathname.match(/^\/api\/stream\/([^/?]+)$/)
        if (mediaMatch && mediaBlobs && mediaBlobs[decodeURIComponent(mediaMatch[1])]) {
            const bytes = mediaBlobs[decodeURIComponent(mediaMatch[1])]
            return send(200, bytes, {
                'content-type': 'video/webm',
                'content-length': String(bytes.length),
                'accept-ranges': 'none'
            })
        }

        const streamMatch = url.pathname.match(/^\/api\/stream\/([^/?]+)/)
        if (streamMatch) {
            const id = decodeURIComponent(streamMatch[1])
            const m = (req.headers.range || '').match(/^bytes=(\d+)-(\d+)$/)
            if (!m) return send(416, '', { 'content-range': 'bytes */' + TOTAL })
            const start = Number(m[1])
            const end = Math.min(Number(m[2]), TOTAL - 1)
            if (id === 'vid-cross' && holdVidCross && start === 0) {
                holdVidCross = false
                await new Promise((r) => setTimeout(r, 900))
            }
            const slice = SOURCE.subarray(start, end + 1)
            return send(206, slice, {
                'content-type': 'video/mp4',
                'content-length': String(slice.length),
                'content-range': `bytes ${start}-${end}/${TOTAL}`,
                'accept-ranges': 'bytes',
                etag: '"range-fixture-1"'
            })
        }
        // Ship the real frontend modules verbatim.
        if (url.pathname.startsWith('/js/') || url.pathname.startsWith('/styles/') || url.pathname.startsWith('/assets/') || url.pathname.startsWith('/fonts/')) {
            try {
                const file = await readFile(join('src/frontend', url.pathname))
                const contentType = url.pathname.endsWith('.css')
                    ? 'text/css; charset=utf-8'
                    : url.pathname.endsWith('.woff2')
                      ? 'font/woff2'
                      : url.pathname.endsWith('.svg')
                        ? 'image/svg+xml'
                        : 'text/javascript; charset=utf-8'
                return send(200, file, { 'content-type': contentType })
            } catch {
                return send(404, 'not found')
            }
        }
        send(404, 'not found')
    })
    return server
}
